function inRing(lng: number, lat: number, ring: Array<[number, number]>) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

// Evenly spaced points over land: rows every `step` degrees of latitude, with the
// longitude spacing widened toward the poles so dots stay roughly equidistant
export function landDots(step = 1.6): Array<{ lat: number; lng: number }> {
  const dots: Array<{ lat: number; lng: number }> = []
  for (let lat = -88; lat <= 88; lat += step) {
    const lngStep = step / Math.max(0.15, Math.cos((lat * Math.PI) / 180))
    for (let lng = -180; lng < 180; lng += lngStep) {
      if (LAND.some((ring) => inRing(lng, lat, ring))) dots.push({ lat, lng })
    }
  }
  return dots
}

// Lat/lng to a point on a sphere of `radius`, in the globe's frame: longitude 0 faces +X
// and east runs toward -Z (the convention SphereGeometry uses for equirectangular maps),
// so z needs the negative sine. Shared by the 3D globe and its loading screen.
export function latLngToXYZ(lat: number, lng: number, radius: number): [number, number, number] {
  const latRad = (lat * Math.PI) / 180
  const lngRad = (lng * Math.PI) / 180
  return [
    Math.cos(latRad) * Math.cos(lngRad) * radius,
    Math.sin(latRad) * radius,
    -Math.cos(latRad) * Math.sin(lngRad) * radius,
  ]
}
